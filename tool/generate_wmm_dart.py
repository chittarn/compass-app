import urllib.request
import math

url = 'https://raw.githubusercontent.com/westphae/geomag/master/pkg/wmm/embedded/WMM.COF'
with urllib.request.urlopen(url) as response:
    lines = response.read().decode('utf-8').strip().split('\n')

MAX_N = 12
G = [[0.0] * (MAX_N + 1) for _ in range(MAX_N + 1)]
H = [[0.0] * (MAX_N + 1) for _ in range(MAX_N + 1)]
DG = [[0.0] * (MAX_N + 1) for _ in range(MAX_N + 1)]
DH = [[0.0] * (MAX_N + 1) for _ in range(MAX_N + 1)]

for line in lines[1:]:
    parts = line.strip().split()
    if len(parts) < 6:
        continue
    if parts[0] == '999999999999999999999999999999999999999999999999':
        break
    n = int(parts[0])
    m = int(parts[1])
    if n > MAX_N:
        continue
    G[n][m] = float(parts[2])
    H[n][m] = float(parts[3])
    DG[n][m] = float(parts[4])
    DH[n][m] = float(parts[5])

# Flatten arrays for clean Dart representation or structured 2D lists
def format_2d(arr):
    out = "[\n"
    for row in arr:
        out += "    [" + ", ".join(f"{x:.6f}" for x in row) + "],\n"
    out += "  ]"
    return out

dart_code = f'''// GENERATED BY tool/generate_wmm_dart.py
// Based on NOAA / British Geological Survey World Magnetic Model (WMM-2025)
// Valid for Epoch 2025.0 to 2030.0 (Degree N=12 spherical harmonic expansion)

import 'dart:math' as math;

/// Complete geomagnetic field components output by WMM-2025
class WmmResult {{
  /// Magnetic Declination in degrees (-180.0 to 180.0).
  /// Positive (+) = East, Negative (-) = West.
  final double declinationDeg;

  /// Magnetic Inclination (dip) in degrees (-90.0 to 90.0).
  /// Positive (+) = Downward (Northern hemisphere), Negative (-) = Upward (Southern hemisphere).
  final double inclinationDeg;

  /// Total magnetic field intensity in nanoTesla (nT).
  final double totalIntensityNt;

  /// Horizontal magnetic field intensity in nanoTesla (nT).
  final double horizontalIntensityNt;

  /// Northerly magnetic field component in nanoTesla (nT).
  final double xNorthNt;

  /// Easterly magnetic field component in nanoTesla (nT).
  final double yEastNt;

  /// Downward magnetic field component in nanoTesla (nT).
  final double zDownNt;

  const WmmResult({{
    required this.declinationDeg,
    required this.inclinationDeg,
    required this.totalIntensityNt,
    required this.horizontalIntensityNt,
    required this.xNorthNt,
    required this.yEastNt,
    required this.zDownNt,
  }});

  @override
  String toString() =>
      'WmmResult(Dec: ${{declinationDeg.toStringAsFixed(2)}}°, Inc: ${{inclinationDeg.toStringAsFixed(2)}}°, F: ${{totalIntensityNt.toStringAsFixed(1)}} nT)';
}}

/// High-precision, fully offline implementation of NOAA/BGS World Magnetic Model (WMM-2025).
///
/// Complies with official NOAA technical specifications:
/// - WGS-84 geodetic reference ellipsoid
/// - Degree N=12 spherical harmonic expansion
/// - Schmidt quasi-normalized associated Legendre polynomials
/// - Secular variation rate interpolation for dates 2025.0–2030.0
class WmmCalculator {{
  static const double epoch = 2025.0;
  static const int maxDegree = 12;

  // WGS-84 Ellipsoid Constants
  static const double _wgs84A = 6378.137; // Semi-major axis in km
  static const double _wgs84B = 6356.7523142; // Semi-minor axis in km
  static const double _meanRadius = 6371.2; // Earth mean radius in km

  // WMM-2025 Spherical Harmonic Gauss Coefficients (nT)
  static const List<List<double>> _g = {format_2d(G)};
  static const List<List<double>> _h = {format_2d(H)};

  // Secular Variation Rates (nT/year)
  static const List<List<double>> _dg = {format_2d(DG)};
  static const List<List<double>> _dh = {format_2d(DH)};

  // Precomputed Schmidt Quasi-Normalization factors
  static final List<List<double>> _schmidt = _computeSchmidtFactors();

  static List<List<double>> _computeSchmidtFactors() {{
    final s = List.generate(maxDegree + 1, (_) => List.filled(maxDegree + 1, 0.0));
    s[0][0] = 1.0;
    for (int n = 1; n <= maxDegree; n++) {{
      s[n][0] = s[n - 1][0] * (2 * n - 1) / n;
      for (int m = 1; m <= n; m++) {{
        s[n][m] = s[n][m - 1] * math.sqrt((n - m + 1) * (m == 1 ? 2.0 : 1.0) / (n + m));
      }}
    }}
    return s;
  }}

  /// Converts a [DateTime] into decimal year (e.g. 2025.5 for July 2, 2025).
  static double dateToDecimalYear(DateTime date) {{
    final year = date.year;
    final startOfYear = DateTime.utc(year, 1, 1);
    final endOfYear = DateTime.utc(year + 1, 1, 1);
    final totalDays = endOfYear.difference(startOfYear).inSeconds;
    final elapsedDays = date.toUtc().difference(startOfYear).inSeconds;
    return year + (elapsedDays / totalDays);
  }}

  /// Calculates the magnetic declination in degrees for a given location and date.
  ///
  /// Positive (+) = East declination (Magnetic North is East of True North).
  /// Negative (-) = West declination (Magnetic North is West of True North).
  ///
  /// [latitudeDeg]: WGS-84 Geodetic latitude in degrees [-90.0, 90.0].
  /// [longitudeDeg]: WGS-84 Geodetic longitude in degrees [-180.0, 180.0].
  /// [altitudeMeters]: Altitude above the WGS-84 ellipsoid in meters (default: 0.0).
  /// [date]: Observation date (default: DateTime.now()).
  static double calculateDeclination({{
    required double latitudeDeg,
    required double longitudeDeg,
    double altitudeMeters = 0.0,
    DateTime? date,
  }}) {{
    final res = calculate(
      latitudeDeg: latitudeDeg,
      longitudeDeg: longitudeDeg,
      altitudeMeters: altitudeMeters,
      date: date,
    );
    return res.declinationDeg;
  }}

  /// Computes the complete 7-component geomagnetic field vector using WMM-2025.
  static WmmResult calculate({{
    required double latitudeDeg,
    required double longitudeDeg,
    double altitudeMeters = 0.0,
    DateTime? date,
  }}) {{
    final decimalYear = date != null ? dateToDecimalYear(date) : dateToDecimalYear(DateTime.now());
    return _computeAtDecimalYear(
      latitudeDeg: latitudeDeg,
      longitudeDeg: longitudeDeg,
      altitudeMeters: altitudeMeters,
      decimalYear: decimalYear,
    );
  }}

  /// Core computation engine matching the official NOAA WMM Fortran/C implementation
  static WmmResult _computeAtDecimalYear({{
    required double latitudeDeg,
    required double longitudeDeg,
    required double altitudeMeters,
    required double decimalYear,
  }}) {{
    // Clamp inputs to valid bounds
    final latClamped = latitudeDeg.clamp(-90.0, 90.0);
    // Normalize longitude to [-180, 180]
    double lonNorm = (longitudeDeg + 180.0) % 360.0;
    if (lonNorm < 0) lonNorm += 360.0;
    lonNorm -= 180.0;

    final altKm = altitudeMeters / 1000.0;

    // 1. Geodetic to Geocentric coordinate transformation on WGS-84 Ellipsoid
    const a = _wgs84A;
    const b = _wgs84B;
    const a2 = a * a;
    const b2 = b * b;
    const a4 = a2 * a2;
    const b4 = b2 * b2;

    final gdLatRad = latClamped * (math.pi / 180.0);
    final gdLonRad = lonNorm * (math.pi / 180.0);
    final cLat = math.cos(gdLatRad);
    final sLat = math.sin(gdLatRad);

    double tLat;
    if (cLat.abs() < 1e-6) {{
      tLat = sLat / (cLat >= 0 ? 1e-6 : -1e-6);
    }} else {{
      tLat = sLat / cLat;
    }}

    final latRad = math.sqrt(a2 * cLat * cLat + b2 * sLat * sLat);
    final gcLatRad = math.atan(tLat * (latRad * altKm + b2) / (latRad * altKm + a2));
    final gcLonRad = gdLonRad;
    final radSq = (altKm * altKm +
        2 * altKm * latRad +
        (a4 * cLat * cLat + b4 * sLat * sLat) / (latRad * latRad));
    final gcRadiusKm = math.sqrt(radSq);

    // 2. Colatitude (theta)
    final thetaRad = (math.pi / 2.0) - gcLatRad;
    final cosTheta = math.cos(thetaRad);
    final sinTheta = math.sin(thetaRad);

    // 3. Associated Legendre Polynomials P_n^m and derivatives
    final p = List.generate(maxDegree + 1, (_) => List.filled(maxDegree + 1, 0.0));
    final pDeriv = List.generate(maxDegree + 1, (_) => List.filled(maxDegree + 1, 0.0));
    p[0][0] = 1.0;
    pDeriv[0][0] = 0.0;

    for (int n = 1; n <= maxDegree; n++) {{
      for (int m = 0; m <= n; m++) {{
        if (n == m) {{
          p[n][m] = sinTheta * p[n - 1][m - 1];
          pDeriv[n][m] = (cosTheta * p[n - 1][m - 1]) + (sinTheta * pDeriv[n - 1][m - 1]);
        }} else if (n == 1 || m == n - 1) {{
          p[n][m] = cosTheta * p[n - 1][m];
          pDeriv[n][m] = (-sinTheta * p[n - 1][m]) + (cosTheta * pDeriv[n - 1][m]);
        }} else {{
          final k = ((n - 1) * (n - 1) - m * m) / ((2 * n - 1) * (2 * n - 3));
          p[n][m] = (cosTheta * p[n - 1][m]) - (k * p[n - 2][m]);
          pDeriv[n][m] = (-sinTheta * p[n - 1][m]) +
              (cosTheta * pDeriv[n - 1][m]) -
              (k * pDeriv[n - 2][m]);
        }}
      }}
    }}

    // 4. Powers of (R_a / r)
    final relRadiusPower = List.filled(maxDegree + 3, 0.0);
    relRadiusPower[0] = 1.0;
    relRadiusPower[1] = _meanRadius / gcRadiusKm;
    for (int i = 2; i < relRadiusPower.length; i++) {{
      relRadiusPower[i] = relRadiusPower[i - 1] * relRadiusPower[1];
    }}

    // 5. Precompute sin(m * lon) and cos(m * lon)
    final cosMLon = List.filled(maxDegree + 1, 0.0);
    final sinMLon = List.filled(maxDegree + 1, 0.0);
    for (int m = 0; m <= maxDegree; m++) {{
      cosMLon[m] = math.cos(m * gcLonRad);
      sinMLon[m] = math.sin(m * gcLonRad);
    }}

    final yearsSinceEpoch = decimalYear - epoch;

    double gcX = 0.0;
    double gcY = 0.0;
    double gcZ = 0.0;

    final invSinTheta = sinTheta.abs() > 1e-6 ? (1.0 / sinTheta) : (1.0 / 1e-6);

    // 6. Spherical Harmonic Summation
    for (int n = 1; n <= maxDegree; n++) {{
      for (int m = 0; m <= n; m++) {{
        final gCoeff = _g[n][m] + (yearsSinceEpoch * _dg[n][m]);
        final hCoeff = _h[n][m] + (yearsSinceEpoch * _dh[n][m]);

        gcX += relRadiusPower[n + 2] *
            (gCoeff * cosMLon[m] + hCoeff * sinMLon[m]) *
            pDeriv[n][m] *
            _schmidt[n][m];

        gcY += relRadiusPower[n + 2] *
            m *
            (gCoeff * sinMLon[m] - hCoeff * cosMLon[m]) *
            p[n][m] *
            _schmidt[n][m] *
            invSinTheta;

        gcZ -= (n + 1) *
            relRadiusPower[n + 2] *
            (gCoeff * cosMLon[m] + hCoeff * sinMLon[m]) *
            p[n][m] *
            _schmidt[n][m];
      }}
    }}

    // 7. Rotate magnetic field components from Geocentric to Geodetic
    final latDiffRad = gdLatRad - gcLatRad;
    final x = (gcX * math.cos(latDiffRad)) + (gcZ * math.sin(latDiffRad));
    final y = gcY;
    final z = (-gcX * math.sin(latDiffRad)) + (gcZ * math.cos(latDiffRad));

    // 8. Compute Declination, Inclination, Horizontal & Total Intensity
    final h = math.sqrt(x * x + y * y);
    final f = math.sqrt(x * x + y * y + z * z);

    double decDeg = math.atan2(y, x) * (180.0 / math.pi);
    double incDeg = math.atan2(z, h) * (180.0 / math.pi);

    // Normalize declination to [-180, 180]
    while (decDeg > 180.0) {{
      decDeg -= 360.0;
    }}
    while (decDeg < -180.0) {{
      decDeg += 360.0;
    }}

    return WmmResult(
      declinationDeg: decDeg,
      inclinationDeg: incDeg,
      totalIntensityNt: f,
      horizontalIntensityNt: h,
      xNorthNt: x,
      yEastNt: y,
      zDownNt: z,
    );
  }}
}}
'''

